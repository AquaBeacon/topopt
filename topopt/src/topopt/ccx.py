def equilibrium_error(applied, reactions):
    """Load/reaction balance (spec 19.4). -> dict with the relative error.

    Statics says the reactions must cancel the applied load exactly; any
    residual is the model disagreeing with itself. It is the cheapest check
    that the boundary conditions in the deck are the ones that were intended,
    and it catches a mis-numbered node set that no stress plot would reveal.

    `reactions` may be None -- that is what `parse_dat` reports for a step
    whose only totals are modal -- and the balance is then reported as
    unchecked rather than raising or, worse, passing.
    """
    if reactions is None:
        return {"error": "CalculiX wrote no reaction total for this step; "
                         "the balance could not be checked", "pass": False}
    a = np.asarray(applied, float).reshape(3)
    r = np.asarray(reactions, float).reshape(3)
    resid = a + r
    mag = float(np.linalg.norm(a))
    rel = float(np.linalg.norm(resid)) / mag if mag > 1e-12 else float("nan")
    return {"applied_N": [round(float(v), 4) for v in a],
            "reaction_N": [round(float(v), 4) for v in r],
            "residual_N": [round(float(v), 6) for v in resid],
            "relative_error": None if np.isnan(rel) else round(rel, 6),
            "pass": bool(mag > 1e-12 and rel <= 0.01),
            "required": "<= 1 % of the applied load"}


def moment_error(applied_points, applied_forces, reaction_points,
                 reaction_forces, about=(0.0, 0.0, 0.0)):
    """Moment balance about `about`. Same idea, one order harder to fake."""
    o = np.asarray(about, float)
    m = np.zeros(3)
    for p, f in zip(applied_points, applied_forces):
        m += np.cross(np.asarray(p, float) - o, np.asarray(f, float))
    mr = np.zeros(3)
    for p, f in zip(reaction_points, reaction_forces):
        mr += np.cross(np.asarray(p, float) - o, np.asarray(f, float))
    resid = m + mr
    mag = float(np.linalg.norm(m))
    rel = float(np.linalg.norm(resid)) / mag if mag > 1e-12 else float("nan")
    return {"applied_Nmm": [round(float(v), 4) for v in m],
            "reaction_Nmm": [round(float(v), 4) for v in mr],
            "residual_Nmm": [round(float(v), 6) for v in resid],
            "relative_error": None if np.isnan(rel) else round(rel, 6),
            "pass": bool(mag > 1e-12 and rel <= 0.01),
            "required": "<= 1 % of the applied moment"}


def compare_with_voxel(voxel_max_disp, ccx_max_disp, tolerance=0.15):
    """Spec 14.4: the difference between the two solvers is always reported.

    A disagreement is not automatically the re-analysis being right -- it is a
    signal to go and find out which of mesh, boundary conditions or material is
    responsible, which is why the verdict carries that instruction.
    """
    if not ccx_max_disp:
        return {"error": "no CalculiX displacement to compare"}
    diff = abs(ccx_max_disp - voxel_max_disp) / max(abs(ccx_max_disp), 1e-12)
    return {"voxel_max_disp_mm": round(float(voxel_max_disp), 5),
            "ccx_max_disp_mm": round(float(ccx_max_disp), 5),
            "relative_difference": round(float(diff), 5),
            "tolerance": tolerance,
            "pass": bool(diff <= tolerance),
            "note": ("within tolerance" if diff <= tolerance else
                     "the two solvers disagree by more than %.0f %%; identify "
                     "whether the mesh, the boundary conditions or the "
                     "material is responsible before using either number"
                     % (100 * tolerance))}


def mesh_convergence(runs, tolerance=0.05, hotspot_tol_mm=None):
    """Spec 15.2: three mesh densities, judged on the change between them.

    `runs` is a list of {"target_mm", "nodes", "max_disp_mm",
    "p99_5_stress_MPa", "hotspot_xyz_mm"} ordered coarse to fine. The verdict
    is about the *last* refinement: if halving the element size still moves
    the answer, the answer is a function of the mesh, not of the part.

    Three conditions, not one:

    - displacement change <= `tolerance` (5 % by default);
    - **p99.5** stress change <= 2 * `tolerance`. The 99.5th percentile is the
      quantity, not the maximum: the maximum on a tet mesh sits on a single
      re-entrant node and grows without limit as the mesh is refined, so a
      criterion written on it can never converge and would condemn a perfectly
      converged part. `max_stress_MPa` is accepted as a fallback for callers
      that only have it, and the note then says the verdict was made on a
      quantity that does not converge;
    - the hotspot must stop moving. A part can hold its numbers steady while
      the worst place migrates from one fillet to another, which means the two
      meshes are not describing the same failure. The default allowance is
      twice the finest element size -- below that the hotspot cannot be
      resolved as having moved at all.
    """
    if len(runs) < 3:
        return {"error": "mesh convergence needs three runs, got %d" % len(runs),
                "pass": False}
    rs = sorted(runs, key=lambda r: -float(r["target_mm"]))
    if hotspot_tol_mm is None:
        hotspot_tol_mm = 2.0 * float(rs[-1]["target_mm"])
    fell_back = any(r.get("p99_5_stress_MPa") is None
                    and r.get("max_stress_MPa") is not None for r in rs)
    out = {"runs": rs, "steps": []}
    for a, b in zip(rs, rs[1:]):
        step = {}
        for key, label in (("max_disp_mm", "displacement"),
                           ("stress", "stress")):
            va = _stress_of(a) if key == "stress" else a.get(key)
            vb = _stress_of(b) if key == "stress" else b.get(key)
            if va is None or vb is None:
                continue
            d = abs(vb - va) / max(abs(vb), 1e-12)
            step[label + "_change"] = round(float(d), 5)
        pa, pb = a.get("hotspot_xyz_mm"), b.get("hotspot_xyz_mm")
        if pa is not None and pb is not None:
            step["hotspot_shift_mm"] = round(float(np.linalg.norm(
                np.asarray(pb, float) - np.asarray(pa, float))), 5)
        out["steps"].append(step)
    last = out["steps"][-1] if out["steps"] else {}
    disp_ok = last.get("displacement_change", 1.0) <= tolerance
    # Stress converges more slowly than displacement on any mesh, so it gets
    # twice the allowance rather than being quietly dropped from the verdict.
    stress_ok = last.get("stress_change", 1.0) <= 2 * tolerance
    shift = last.get("hotspot_shift_mm")
    hotspot_ok = shift is None or shift < hotspot_tol_mm
    ok = bool(disp_ok and stress_ok and hotspot_ok)
    out["tolerance"] = tolerance
    out["hotspot_tolerance_mm"] = round(float(hotspot_tol_mm), 5)
    out["pass"] = ok
    note = ("the finest refinement changed the answer by less than the "
            "tolerance" if ok else
            "the answer is still moving with the mesh; it is a property "
            "of the discretisation, not of the part")
    if ok is False and disp_ok and stress_ok and not hotspot_ok:
        note = ("the numbers settled but the hotspot moved %.2f mm (allowed "
                "%.2f); the two meshes are not describing the same failure, "
                "so it is a property of the discretisation, not of the part"
                % (shift, hotspot_tol_mm))
    if fell_back:
        note += ("; p99.5 stress was not reported, so max_stress_MPa was used "
                 "-- the maximum on a tet mesh does not converge and this "
                 "part of the verdict is weaker than it looks")
    out["note"] = note
    return out


def _stress_of(run):
    """The stress a convergence run is judged on: p99.5 first, max as a
    fallback. Never a silent choice -- `mesh_convergence` says in its note
    when it had to take the maximum."""
    v = run.get("p99_5_stress_MPa")
    return run.get("max_stress_MPa") if v is None else v


def compare_cases(voxel_cases, ccx_cases, tolerance=0.15):
    """Spec 14.4, case by case: the voxel FEA against the CalculiX re-analysis.

    -> {"cases": [...], "pass", "within", "total", "note",
        "unmatched_voxel", "unmatched_ccx"}

    Comparing only the governing case hides the interesting failure: the two
    solvers can agree on the worst case and disagree by 40 % on another, which
    is what osmo_tripod actually did (4 of 6 cases outside 15 %, known-issues
    A6). So every case is paired and reported.

    Pairing is on the **first token** of the case name, because the two paths
    grew different long names for the same case ("LC3x" against
    "LC3x lateral 30 N"). A name that pairs with nothing is listed rather than
    dropped: a case missing from one side is not agreement.
    """
    def key(name):
        return str(name or "").split()[0] if str(name or "").split() else ""

    vmap, cmap = {}, {}
    for c in voxel_cases or ():
        vmap.setdefault(key(c.get("case")), []).append(c)
    for c in ccx_cases or ():
        cmap.setdefault(key(c.get("case")), []).append(c)

    rows, within = [], 0
    for k in [k for k in vmap if k in cmap]:
        v, c = vmap[k][0], cmap[k][0]
        vd, cd = v.get("max_displacement_mm"), c.get("max_disp_mm")
        row = {"case": c.get("case"), "voxel_case": v.get("case"),
               "voxel_max_disp_mm": vd, "ccx_max_disp_mm": cd,
               "voxel_safety_factor_p99_5": v.get("safety_factor_p99_5"),
               "voxel_min_safety_factor": v.get("min_safety_factor"),
               "ccx_safety_factor_p99_5": c.get("safety_factor_p99_5"),
               "ccx_worst_element_safety_factor":
                   c.get("worst_element_safety_factor")}
        if vd is None or cd is None:
            row.update({"pass": False,
                        "note": "one of the two runs has no displacement"})
        else:
            vd, cd = float(vd), float(cd)
            diff = abs(cd - vd) / max(abs(cd), 1e-12)
            row["ratio_ccx_over_voxel"] = (round(cd / vd, 5) if abs(vd) > 1e-12
                                           else None)
            row["relative_difference"] = round(diff, 5)
            row["pass"] = bool(diff <= tolerance)
            within += int(row["pass"])
        rows.append(row)
    rows.sort(key=lambda r: str(r["case"]))

    ccx_only = sorted(k for k in cmap if k not in vmap)
    voxel_only = sorted(k for k in vmap if k not in cmap)
    total = len(rows)
    ok = bool(total and within == total and not ccx_only and not voxel_only)
    note = ("every case agrees within %.0f %%" % (100 * tolerance) if ok else
            "%d of %d cases disagree by more than %.0f %%; identify whether "
            "the mesh, the boundary conditions or the material is responsible "
            "before using either number"
            % (total - within, total, 100 * tolerance))
    if ccx_only or voxel_only:
        note += ("; unpaired case names: %s"
                 % ", ".join(voxel_only + ccx_only))
    return {"cases": rows, "pass": ok, "within": within, "total": total,
            "tolerance": tolerance, "unmatched_voxel": voxel_only,
            "unmatched_ccx": ccx_only, "note": note}
