def shell_check(stl_path):
    """-> `geom.shell_report` of the STL. Gmsh builds the tet mesh on the
    STL's own triangles, so a shell that is not closed (degenerate triangles,
    non-manifold edges) is not a warning: it is the "PLC Error: a segment and
    a facet intersect" the first real run stopped on, and with surface
    reclassification it is a fifteen-minute hang instead. Cheaper to look
    first."""
    from .geom import load_stl, shell_report
    return shell_report(load_stl(stl_path))


def refine_triangles(tri, max_edge_mm, max_passes=40):
    """Split every edge longer than `max_edge_mm` at its midpoint until none
    is. -> (triangles (m,3,3), passes).

    Both triangles sharing an edge split it at the same point, so a closed
    shell stays closed and the surface does not move: every new vertex lies
    on an existing edge. Facets stay planar, which is the point -- the STL
    *is* the shape that gets printed, and reparametrising it (Gmsh's
    ClassifySurfaces) both moves the surface and, on osmo_tripod, stops with
    "overlapping facets". Splitting only ever adds detail the mesher can use.
    """
    tri = np.asarray(tri, float)
    for it in range(max_passes):
        v = tri.reshape(-1, 3)
        uniq, inv = np.unique(np.round(v, 6), axis=0, return_inverse=True)
        F = inv.reshape(-1, 3)
        P = uniq
        es = np.sort(np.stack([F[:, [0, 1]], F[:, [1, 2]], F[:, [2, 0]]],
                              axis=1), axis=2)                  # (m,3,2)
        L = np.linalg.norm(P[es[:, :, 0]] - P[es[:, :, 1]], axis=2)
        need = L > max_edge_mm
        if not need.any():
            return tri, it
        S = set(map(tuple, es[need].reshape(-1, 2)))
        mid = {}

        def m(a, b):
            k = (min(a, b), max(a, b))
            if k not in mid:
                mid[k] = (P[a] + P[b]) / 2.0
            return mid[k]

        out = []
        for t in range(len(F)):
            ids = [int(x) for x in F[t]]
            split = [tuple(sorted((ids[0], ids[1]))) in S,
                     tuple(sorted((ids[1], ids[2]))) in S,
                     tuple(sorted((ids[2], ids[0]))) in S]
            ns = sum(split)
            if ns == 0:
                out.append(P[ids])
                continue
            if ns == 3:
                A, B, C = P[ids]
                ab, bc, ca = (m(ids[0], ids[1]), m(ids[1], ids[2]),
                              m(ids[2], ids[0]))
                out += [(A, ab, ca), (ab, B, bc), (ca, bc, C), (ab, bc, ca)]
                continue
            # Rotate so the split edge is A-B; the templates below only add
            # points on edges, so whichever diagonal they choose inside the
            # triangle stays conforming with the neighbour.
            while not split[0]:
                split = split[1:] + split[:1]
                ids = ids[1:] + ids[:1]
            A, B, C = P[ids]
            ab = m(ids[0], ids[1])
            if ns == 1:
                out += [(A, ab, C), (ab, B, C)]
            elif split[1]:
                bc = m(ids[1], ids[2])
                out += [(A, ab, C), (ab, bc, C), (ab, B, bc)]
            else:
                ca = m(ids[2], ids[0])
                out += [(A, ab, ca), (ab, B, C), (ab, C, ca)]
        tri = np.array(out, float)
    return tri, max_passes


def refine_stl(src, dst, max_edge_mm):
    """Write `src` refined so no edge is longer than `max_edge_mm` to `dst`.
    -> {"triangles_before", "triangles_after", "max_edge_before_mm",
        "max_edge_after_mm", "passes", "path"}."""
    from .geom import load_stl
    from .stepio import write_binary_stl

    def longest(t):
        if len(t) == 0:
            return 0.0
        return float(max(np.linalg.norm(t[:, 1] - t[:, 0], axis=1).max(),
                         np.linalg.norm(t[:, 2] - t[:, 1], axis=1).max(),
                         np.linalg.norm(t[:, 0] - t[:, 2], axis=1).max()))
    tri = load_stl(src)
    out, passes = refine_triangles(tri, max_edge_mm)
    n = np.cross(out[:, 1] - out[:, 0], out[:, 2] - out[:, 0])
    write_binary_stl(dst, [(n[i], out[i, 0], out[i, 1], out[i, 2])
                           for i in range(len(out))])
    return {"triangles_before": int(len(tri)), "triangles_after": int(len(out)),
            "max_edge_before_mm": round(longest(tri), 3),
            "max_edge_after_mm": round(longest(out), 3),
            "passes": int(passes), "path": dst}


def repair_stl(src, dst):
    """Rebuild a dirty STL shell with MeshFix (the `pymeshfix` package) and
    write it to `dst`. -> {"before": report, "after": report,
    "volume_before_mm3", "volume_after_mm3"}.

    OpenSCAD 2021's CGAL output regularly carries zero-area triangles and a
    few non-manifold edges where unioned solids touch; MeshFix removes them
    without moving the surface (osmo_tripod: 2052 -> 2048 triangles, volume
    unchanged to 0.1 mm3). It is optional: `pymeshfix` is not a dependency
    of this toolkit, and the caller decides what to do when it is absent.
    """
    import numpy as np
    from .geom import load_stl, shell_report
    from .stepio import write_binary_stl
    try:
        import pymeshfix
    except ImportError as exc:
        raise ImportError(
            "repairing an STL needs the `pymeshfix` package "
            "(pip install pymeshfix); it is optional and not installed") from exc
    tri = load_stl(src)
    before = shell_report(tri)
    v = tri.reshape(-1, 3)
    uniq, inv = np.unique(v.round(6), axis=0, return_inverse=True)
    faces = inv.reshape(-1, 3)
    mf = pymeshfix.MeshFix(uniq, faces)
    mf.repair(joincomp=True, remove_smallest_components=False)
    fixed = np.asarray(mf.points, float)[np.asarray(mf.faces).reshape(-1, 3)]
    normals = np.cross(fixed[:, 1] - fixed[:, 0], fixed[:, 2] - fixed[:, 0])
    write_binary_stl(dst, [(n, t[0], t[1], t[2]) for n, t in zip(normals, fixed)])
    after = shell_report(load_stl(dst))

    def volume(t):
        return float(np.einsum("ij,ij->i", t[:, 0],
                               np.cross(t[:, 1], t[:, 2])).sum() / 6.0)
    return {"before": before, "after": after,
            "volume_before_mm3": round(volume(tri), 2),
            "volume_after_mm3": round(volume(fixed), 2), "path": dst}


def parse_frd(path):
    """Read displacements and stresses out of a CalculiX .frd file.

    -> {"nodes": {id: (x,y,z)}, "displacement": {id: (ux,uy,uz)},
        "stress": {id: (sxx,syy,szz,sxy,syz,szx)},
        "strain": {id: (exx,eyy,ezz,exy,eyz,ezx)},
        "reaction": {id: (fx,fy,fz)},
        "steps": [{"step": n, "displacement": {...}, "stress": {...},
                   "strain": {...}, "reaction": {...}}, ...]}

    The strain comes from the frd's `TOSTRAIN` block and the nodal forces from
    its `FORC` block, both of which `*EL FILE: S, E` and `*NODE FILE: U, RF`
    already ask for -- they were simply being thrown away. The strain shear
    components are **tensor** strains, not engineering ones: measured on a real
    2.23 run, sxy / exy came out at exactly 2*Gxy (2000 for Gxy = 1000 MPa),
    which is the ratio only a tensor component gives. `strain_energy_density`
    is written for that convention.

    `displacement` / `stress` at the top level are the *last* step's, kept
    for callers that only ever had one. A multi-case deck is one step per
    case, and each step's results live in `steps` -- reading the top level
    for a six-case study reports case six and calls it the part (which is
    what happened on the first real run, 2026-09-08).

    The .frd blocks are fixed-width, but CalculiX writes both a 12-column and a
    13-column variant depending on version, so fields are split on whitespace
    after the leading record marker rather than sliced by position.
    """
    nodes = {}
    steps = []
    cur = None
    mode = None

    def step_block(num):
        for st in steps:
            if st["step"] == num:
                return st
        st = {"step": num, "displacement": {}, "stress": {},
              "strain": {}, "reaction": {}}
        steps.append(st)
        return st

    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            s = line.rstrip("\n")
            if not s:
                continue
            head = s.strip()
            if head.startswith("2C"):
                mode = "nodes"
                continue
            if head.startswith("100C"):
                # "100CL  101 1.000000000  <nnodes>  0  <step>  1": the step
                # number is the sixth field. A file with no such header (an
                # old single-step deck, or the test fixture) is step 1.
                toks = head.split()
                try:
                    # A frequency step writes the number glued to a tag --
                    # "2    7MODAL      1" -- so the field is not a bare int.
                    cur = step_block(int(re.match(r"\d+", toks[5]).group()))
                except (IndexError, ValueError, AttributeError):
                    cur = step_block(len(steps) + 1)
                continue
            if "DISP" in head and head.startswith("-4"):
                mode = "disp"
                if cur is None:
                    cur = step_block(1)
                continue
            if "STRESS" in head and head.startswith("-4"):
                mode = "stress"
                if cur is None:
                    cur = step_block(1)
                continue
            if "TOSTRAIN" in head and head.startswith("-4"):
                mode = "strain"
                if cur is None:
                    cur = step_block(1)
                continue
            if "FORC" in head and head.startswith("-4"):
                # The nodal force block. At a supported node this is the
                # reaction; everywhere else it is the applied load, so the
                # two together are the residual the equilibrium check needs.
                mode = "reaction"
                if cur is None:
                    cur = step_block(1)
                continue
            if head.startswith("-3"):
                mode = None
                continue
            if head.startswith("-5"):
                continue                        # component declaration
            if not head.startswith("-1"):
                continue
            got = _frd_record(s)
            if got is None:
                continue
            nid, vals = got
            if mode == "nodes" and len(vals) >= 3:
                nodes[nid] = tuple(vals[:3])
            elif mode == "disp" and len(vals) >= 3:
                cur["displacement"][nid] = tuple(vals[:3])
            elif mode == "stress" and len(vals) >= 6:
                # CalculiX writes SXX SYY SZZ SXY SYZ SZX -- the same order
                # this codebase uses, which is why no permutation happens here.
                cur["stress"][nid] = tuple(vals[:6])
            elif mode == "strain" and len(vals) >= 6:
                # EXX EYY EZZ EXY EYZ EZX -- the same order again, and the
                # shears are tensor components (see the docstring).
                cur["strain"][nid] = tuple(vals[:6])
            elif mode == "reaction" and len(vals) >= 3:
                cur["reaction"][nid] = tuple(vals[:3])
    last = (steps[-1] if steps else
            {"displacement": {}, "stress": {}, "strain": {}, "reaction": {}})
    return {"nodes": nodes, "displacement": last["displacement"],
            "stress": last["stress"], "strain": last["strain"],
            "reaction": last["reaction"], "steps": steps}


def _frd_record(line):
    """-> (node id, [values]) from one `-1` record, or None.

    The .frd format is **fixed width**: 3 columns for the record marker, 10 for
    the node number, then 12 per value. Splitting on whitespace looks like it
    works and then loses data the moment a value is negative, because
    `0.00000E+00-5.00000E-02` has no space in it. That is not an edge case --
    half the displacements in any real result are negative.

    A whitespace split is kept as a fallback for the wider node-number variant
    CalculiX writes for large models, where the fixed columns shift.
    """
    body = line.rstrip("\n")
    try:
        nid = int(body[3:13])
        rest = body[13:]
        vals = []
        for i in range(0, len(rest), 12):
            chunk = rest[i:i + 12].strip()
            if chunk:
                vals.append(float(chunk))
        if vals:
            return nid, vals
    except (ValueError, IndexError):
        pass
    parts = body.split()
    try:
        return int(parts[1]), [float(v) for v in parts[2:]]
    except (ValueError, IndexError):
        return None


def parse_dat(path):
    """-> {"reaction_totals": [...], "reaction_blocks": [...],
           "buckling_factors": [...], "frequencies_hz": [...]}.

    Written against a real CalculiX 2.23 `.dat`, because the format is not
    what it reads like from the manual:

    - **The section headers are spelled out letter by letter with spaces**:
      ``B U C K L I N G   F A C T O R   O U T P U T`` and
      ``E I G E N V A L U E   O U T P U T``. A parser looking for
      "buckling factor" finds nothing and reports an empty list, which is
      indistinguishable from a part that did not buckle. Every header here is
      matched with the spaces squeezed out.
    - **The values do not start on the next line.** A blank line and two or
      three column-heading lines come first, so the scan skips ahead to the
      first line that parses as numbers and stops at the blank line after
      them -- stopping at the first non-numeric line would return nothing,
      and not stopping would swallow the participation factors that follow.
    - **A frequency row is** ``mode, eigenvalue, rad/time, cycles/time,
      imaginary``. Hz is the *cycles/time* column: eigenvalue 4.5817e8 gives
      omega 2.1405e4 rad/s and f 3.4067e3 Hz. Reporting rad/s as Hz would
      overstate every natural frequency by 2*pi.
    - **"total force" appears far more often than there are steps.** A
      buckling step prints one for the reference load and one per mode, and a
      frequency step prints one per mode; with several support sets there is
      one per set as well. So the blocks are grouped -- a new group at every
      ``S T E P`` and every ``E I G E N V A L U E   N U M B E R`` -- and
      `reaction_totals` is the sum over the *first* group of each step: one
      entry per step, in step order, which is the indexing the caller uses.
      A step whose only totals are modal (the frequency step) gets ``None``,
      because a modal reaction is not a load balance and writing zero there
      would look like a part in equilibrium. `reaction_blocks` keeps every
      block untouched for when a step total looks wrong.
    """
    out = {"reaction_totals": [], "reaction_blocks": [],
           "buckling_factors": [], "frequencies_hz": []}
    if not os.path.exists(path):
        return out
    with open(path, encoding="utf-8", errors="replace") as f:
        lines = f.read().splitlines()

    steps = []          # [{"step": n, "groups": [[ (fx,fy,fz), ... ], ...]}]

    def new_step(num):
        steps.append({"step": num, "groups": [[]]})
        return steps[-1]

    def new_group():
        if not steps:
            new_step(len(steps) + 1)
        steps[-1]["groups"].append([])

    i = 0
    while i < len(lines):
        squashed = "".join(lines[i].split()).lower()
        if re.match(r"^step\d+$", squashed):
            new_step(int(squashed[4:]))
        elif squashed.startswith("eigenvaluenumber"):
            new_group()
        elif "totalforce" in squashed:
            for j in range(i + 1, min(i + 5, len(lines))):
                v = _floats(lines[j])
                if len(v) >= 3:
                    if not steps:
                        new_step(1)
                    steps[-1]["groups"][-1].append(tuple(v[-3:]))
                    out["reaction_blocks"].append(
                        {"step": steps[-1]["step"],
                         "set": _dat_set_name(lines[i]),
                         "force": tuple(v[-3:])})
                    i = j
                    break
        elif "bucklingfactor" in squashed:
            out["buckling_factors"].extend(
                v[-1] for v in _dat_table(lines, i + 1, 2))
        elif squashed.startswith("eigenvalueoutput"):
            out["frequencies_hz"].extend(
                v[3] for v in _dat_table(lines, i + 1, 4))
        i += 1

    for st in steps:
        first = st["groups"][0]
        if not first:
            out["reaction_totals"].append(None)
            continue
        tot = [0.0, 0.0, 0.0]
        for f in first:
            for d in range(3):
                tot[d] += f[d]
        out["reaction_totals"].append(tuple(tot))
    return out


def _dat_set_name(header):
    """The node set a "total force" block belongs to, or None."""
    m = re.search(r"(?i)for set\s+(\S+)", header)
    return m.group(1) if m else None


def _dat_table(lines, start, ncols):
    """Rows of a `.dat` results table: skip the headings, stop after the data.

    A CalculiX table is header, blank line, two or three column-caption lines,
    blank line, then the rows. So "the next line" is never the data and "the
    first line without numbers" is always a caption -- both of the obvious
    stopping rules return an empty table.
    """
    rows, started = [], False
    for j in range(start, len(lines)):
        v = _floats(lines[j])
        if len(v) >= ncols and float(v[0]).is_integer():
            rows.append(v)
            started = True
        elif started:
            break
    return rows


def _floats(line):
    out = []
    for tok in line.replace(",", " ").split():
        try:
            out.append(float(tok))
        except ValueError:
            return out if out else []
    return out


# -------------------------------------------------- stress post-processing

def _voigt_to_matrix(sig6):
    """(n,6) [xx,yy,zz,xy,yz,zx] -> (n,3,3) symmetric matrices."""
    s = np.atleast_2d(np.asarray(sig6, float))
    if s.shape[-1] != 6:
        raise ValueError("expected (n,6) Voigt components, got %r"
                         % (s.shape,))
    m = np.zeros(s.shape[:-1] + (3, 3))
    m[..., 0, 0], m[..., 1, 1], m[..., 2, 2] = s[..., 0], s[..., 1], s[..., 2]
    m[..., 0, 1] = m[..., 1, 0] = s[..., 3]
    m[..., 1, 2] = m[..., 2, 1] = s[..., 4]
    m[..., 2, 0] = m[..., 0, 2] = s[..., 5]
    return m


def principal_stresses(sig6):
    """(n,6) Voigt stress -> (n,3) principal stresses, largest first.

    Voigt order here is [xx, yy, zz, xy, yz, zx] -- the order `parse_frd`
    returns and the one the rest of this codebase uses. `eigvalsh` returns
    ascending, so the reversal is not cosmetic: sigma_1 is the number a
    brittle-failure criterion wants, and getting sigma_3 instead reports the
    most compressed direction as the most stretched one.
    """
    w = np.linalg.eigvalsh(_voigt_to_matrix(sig6))
    return w[..., ::-1]


def principal_strains(eps6):
    """(n,6) Voigt strain -> (n,3) principal strains, largest first.

    **The shear components are used as they come.** `parse_frd`'s `TOSTRAIN`
    block holds *tensor* shear strains -- measured, not assumed: on this
    module's own deck sxy/exy came back at exactly 2*Gxy, which only a tensor
    component gives (see `strain_energy_density`). The eigenvalues of the
    strain tensor need tensor shears, so an engineering-strain input would
    have to be halved first, and doing it the wrong way round is invisible in
    a uniaxial check and wrong by up to a factor of two in shear.
    """
    w = np.linalg.eigvalsh(_voigt_to_matrix(eps6))
    return w[..., ::-1]


def tresca(sig6):
    """(n,6) Voigt stress -> (n,) Tresca equivalent stress, sigma_1 - sigma_3.

    Reported alongside von Mises rather than instead of it: Tresca is the
    conservative one (it equals 2*tau in pure shear where von Mises reads
    sqrt(3)*tau, about 15 % lower), so a part that passes on von Mises and
    fails on Tresca is a part whose margin is inside the difference between
    two textbook criteria.
    """
    p = principal_stresses(sig6)
    return p[..., 0] - p[..., 2]


def strain_energy_density(sig6, eps6):
    """Strain energy per unit volume, mJ/mm^3, from stress and strain.

    **The frd `TOSTRAIN` shear components are tensor strains, not engineering
    ones.** Measured on a real CalculiX 2.23 run of this module's own deck:
    sxy / exy came back at exactly 2*Gxy (2000 MPa for Gxy = 1000 MPa), which
    is the ratio only a tensor component gives -- an engineering component
    would have read Gxy. So the energy is the full tensor contraction

        u = 1/2 (sxx exx + syy eyy + szz ezz) + sxy exy + syz eyz + szx ezx

    with no factor of 1/2 on the shear terms. Assuming engineering strain here
    would halve the shear contribution and understate the energy in exactly
    the shear-dominated regions where it matters.
    """
    s = np.atleast_2d(np.asarray(sig6, float))
    e = np.atleast_2d(np.asarray(eps6, float))
    if s.shape != e.shape or s.shape[-1] != 6:
        raise ValueError("stress and strain must both be (n,6); got %r and %r"
                         % (s.shape, e.shape))
    return (0.5 * (s[..., :3] * e[..., :3]).sum(axis=-1)
            + (s[..., 3:] * e[..., 3:]).sum(axis=-1))


