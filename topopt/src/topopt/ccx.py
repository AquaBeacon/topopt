"""CalculiX deck generation and result parsing (spec 14).

Why re-analyse at all
---------------------
Checking the optimiser with the optimiser proves nothing: the same code on the
same discretisation makes the same systematic errors twice and they cancel.
The re-analysis is only worth running because it is a *different* solver on a
*different* mesh -- tetrahedra from Gmsh instead of the voxel grid, CalculiX's
assembly instead of the matrix-free CG here.

Layout of this module
---------------------
Everything except the two `subprocess` calls is a pure function, on purpose.
Neither Gmsh nor CalculiX is a dependency of this project, so on a machine
without them the deck writer and the result parser are still the parts most
likely to be wrong, and they stay testable: `write_inp` produces text and
`parse_frd` / `parse_dat` consume text.

The orthotropic card
--------------------
CalculiX's `*ELASTIC, TYPE=ORTHO` wants nine constants in *its* order, which is
D1111 D1122 D2222 D1133 D2233 D3333 D1212 D1313 D2323 -- upper triangle of the
normal block by columns, then the three shears in the order xy, zx, yz. That is
neither this codebase's Voigt order nor the textbook one, so the mapping is
written out explicitly below rather than inferred.
"""

import os
import re
import subprocess

import numpy as np

from .external import require


# ------------------------------------------------------------------ meshing

GEO_TEMPLATE = """// generated by topopt -- tetrahedral mesh for the CalculiX re-analysis
Merge "{stl}";
Surface Loop(1) = {{1}};
Volume(1) = {{1}};
Physical Volume("part") = {{1}};
Mesh.CharacteristicLengthMin = {lmin:.6g};
Mesh.CharacteristicLengthMax = {lmax:.6g};
Mesh.Algorithm3D = {algo};             // 10 = HXT (1 = Delaunay is 10x slower on a refined shell)
Mesh.ElementOrder = 2;             // C3D10: linear tets lock in bending
Mesh.SecondOrderIncomplete = 0;
Mesh.Optimize = 1;
Mesh.OptimizeNetgen = 1;
"""


# Gmsh's 3D algorithms: 1 = Delaunay, 4 = Frontal, 10 = HXT. HXT is the
# default because on a shell refined to the target size (`refine_stl`) it
# meshed osmo_tripod's 40k-triangle surface in 67 s where Delaunay had not
# finished after 12 minutes (2026-09-08).
GMSH_ALGORITHM_3D = 10


def write_geo(path, stl_path, target_mm, algorithm=GMSH_ALGORITHM_3D):
    """A Gmsh input that meshes an STL shell into second-order tets.

    Second order is not a refinement knob here, it is a correctness one: linear
    tets shear-lock in bending and report a beam several times stiffer than it
    is -- the direction of error that lets a weak part pass, which is the same
    reason the voxel element carries incompatible modes.

    **The STL's triangles become the surface mesh unchanged.** Gmsh treats a
    merged STL as a discrete surface and only fills the inside; the
    characteristic length governs the interior, never the boundary. Measured
    (osmo_tripod, 2026-09-08): 2048 STL triangles in, 2048 boundary faces out
    at 4, 2 and 1 mm alike. So a "mesh convergence" study on a raw STL refines
    nothing where the stress lives, and a support mapped to surface nodes
    sees the STL's vertices (nine per foot) whatever the target size. Refine
    the shell first with `refine_stl`; the CLI does.
    """
    txt = GEO_TEMPLATE.format(stl=os.path.abspath(stl_path).replace("\\", "/"),
                              lmin=0.5 * target_mm, lmax=target_mm,
                              algo=int(algorithm))
    with open(path, "w", encoding="utf-8") as f:
        f.write(txt)
    return path


def run_gmsh(geo_path, out_path, timeout=1800):
    """-> path to the .inp mesh. Raises ToolMissing (exit code 3) without Gmsh."""
    exe = require("gmsh", "meshing the extracted shape for CalculiX")
    cmd = [exe, geo_path, "-3", "-format", "inp", "-o", out_path]
    r = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    if r.returncode != 0 or not os.path.exists(out_path):
        raise RuntimeError("gmsh failed (%d):\n%s"
                           % (r.returncode, (r.stderr or r.stdout)[-4000:]))
    return out_path


# ------------------------------------------------------------- mesh reading

# Node counts of the element types this reader understands. The .geo always
# asks for order 2, so C3D10 is what Gmsh writes; C3D4 is here because a mesh
# that quietly came back linear must be *reported* as linear, not crash the
# reader and be blamed on the file.
TET_TYPES = {"C3D10": 10, "C3D4": 4}


def read_mesh(path):
    """Read a Gmsh `.inp` mesh. -> {"ids", "xyz", "elements", "types"}.

    `ids` are the node numbers as written (1-based), `xyz` is (n,3) in the same
    order, `elements` is (m,10) -- or (m,4) for a linear mesh -- of *node ids*,
    and `types` lists every `*ELEMENT` type seen in the file.

    Three things about the real file (Gmsh 4.15.2) that a reader written from
    the Abaqus manual gets wrong:

    - the element block header is ``*ELEMENT, type=C3D10, ELSET=Volume1``:
      lower-case ``type=``, and the set is *not* the physical volume's name.
      ``part`` exists only as a separate ``*ELSET,ELSET=part`` block, so
      collecting elements by set name would find none.
    - ``*Heading`` is followed by a bare file path, and the element block is
      preceded by ``******* E L E M E N T S *************``. Neither is a card
      and neither is data; a reader that does not skip them either parses a
      Windows path as a node or stops at the first line it cannot float().
    - Abaqus allows an element line to continue on the next line. Gmsh writes
      C3D10 unwrapped (11 fields fit on one line), but it *does* use
      trailing-comma continuation in the ``*ELSET`` block, so continuation
      here is driven off "I still have fewer nodes than this type needs"
      rather than off a trailing comma -- the comma alone would make the
      element reader's behaviour depend on a block it is not reading.
    """
    ids, xyz = [], []
    by_type = {}
    types = []
    mode = None
    etype = None
    pending = []
    with open(path, encoding="utf-8", errors="replace") as f:
        for line in f:
            s = line.strip()
            if not s or s.startswith("**"):
                continue                       # comment / banner, not a card
            if s.startswith("*"):
                up = s.upper()
                pending = []
                if up.startswith("*NODE"):
                    mode, etype = "node", None
                elif up.startswith("*ELEMENT"):
                    etype = _inp_keyword(s, "TYPE") or ""
                    types.append(etype)
                    mode = "elem" if etype in TET_TYPES else None
                else:
                    mode, etype = None, None
                continue
            if mode == "node":
                p = [t for t in s.split(",") if t.strip()]
                if len(p) >= 4:
                    try:
                        nid = int(p[0])
                        pt = [float(v) for v in p[1:4]]
                    except ValueError:
                        mode = None            # the *Heading path, not a node
                        continue
                    ids.append(nid)
                    xyz.append(pt)
            elif mode == "elem":
                try:
                    pending.extend(int(t) for t in s.split(",") if t.strip())
                except ValueError:
                    pending = []
                    continue
                need = TET_TYPES[etype] + 1
                while len(pending) >= need:
                    by_type.setdefault(etype, []).append(pending[1:need])
                    pending = pending[need:]
    if not ids:
        raise RuntimeError("no nodes in %s -- the mesh is empty" % path)
    # Second order wins when both are present: the deck was written for it,
    # and silently analysing the linear subset would report a stiffer part.
    order = [t for t in ("C3D10", "C3D4") if by_type.get(t)]
    elements = (np.array(by_type[order[0]], int) if order
                else np.zeros((0, 10), int))
    return {"ids": np.array(ids, int), "xyz": np.array(xyz, float),
            "elements": elements, "types": types}


def _inp_keyword(card, key):
    """The value of `key=` on an Abaqus card, case-insensitively."""
    m = re.search(r"(?i)\b%s\s*=\s*([^,\s]+)" % re.escape(key), card)
    return m.group(1) if m else None


# Corner-node triangles of a tet, and the midside node sitting on each of
# their edges. Abaqus C3D10 order, verified against a real Gmsh mesh (all six
# midsides within 2e-13 mm of their edge midpoint):
# n5=(1,2) n6=(2,3) n7=(3,1) n8=(1,4) n9=(2,4) n10=(3,4).
_TET_FACES = ((0, 1, 2), (0, 1, 3), (0, 2, 3), (1, 2, 3))
_EDGE_MIDSIDE = {(0, 1): 4, (1, 2): 5, (0, 2): 6,
                 (0, 3): 7, (1, 3): 8, (2, 3): 9}


def _face_table(elements):
    """-> (elements, (4m,3) corner faces, (4m,) bool "this face has one owner").

    Shared by `surface_nodes` and `surface_faces` so the two can never
    disagree about what the boundary is: a clamp reported over an area the
    node set does not cover is worse than no area at all.
    """
    el = np.asarray(elements, int)
    if el.size == 0:
        return el, np.zeros((0, 3), int), np.zeros(0, bool)
    faces = np.concatenate([el[:, list(f)] for f in _TET_FACES], axis=0)
    key = np.sort(faces, axis=1)
    _uniq, inv, counts = np.unique(key, axis=0, return_inverse=True,
                                   return_counts=True)
    return el, faces, counts[inv.reshape(-1)] == 1


def surface_faces(elements):
    """Boundary triangles of a tet mesh, corner nodes only. -> (k,3) node ids.

    Same rule as `surface_nodes` -- a face with one owner instead of two is on
    the boundary -- but the faces themselves, so a caller can measure how much
    area a support actually holds. A support is reported by node count today,
    and a node count says nothing: the same twelve nodes are a postage stamp
    on a fine mesh and half the part on a coarse one.

    Only the three corners are returned. A C3D10 boundary face covers exactly
    the same patch as its corner triangle, and the corner triangle is what the
    area integral needs; the midside nodes would double-count it.
    """
    _el, faces, outer = _face_table(elements)
    return faces[outer]


def face_areas(faces, xyz, ids=None):
    """Areas (mm^2) of the triangles in `faces`. -> (k,) array.

    `xyz` may be a {node id: (x,y,z)} mapping or an (n,3) array; with an array
    and no `ids` the node ids are taken to be its row index plus one, which is
    what Gmsh writes. Same rule as `_corner_points`, and for the same reason:
    an off-by-one gives a perfectly plausible area for the wrong patch.
    """
    f = np.asarray(faces, int)
    if len(f) == 0:
        return np.zeros(0)
    if isinstance(xyz, dict):
        p = np.array([[xyz[int(n)] for n in row] for row in f], float)
    else:
        pts = np.asarray(xyz, float)
        if ids is not None:
            lookup = {int(v): i for i, v in enumerate(np.asarray(ids, int))}
            p = pts[np.array([[lookup[int(n)] for n in row] for row in f], int)]
        else:
            p = pts[f - 1]
    return 0.5 * np.linalg.norm(np.cross(p[:, 1] - p[:, 0],
                                         p[:, 2] - p[:, 0]), axis=1)


def surface_nodes(elements):
    """Node ids on the boundary of a tet mesh. -> sorted np.ndarray(int).

    A face is on the boundary exactly when it belongs to one element instead
    of two. The alternative -- a geometric test against the STL -- depends on
    a tolerance and quietly drops nodes on a curved wall.

    For C3D10 the three midside nodes of a boundary face come with it: a
    boundary condition put on the corners only of a second-order face leaves
    the midside free and lets the face flap, which is a clamp that is not a
    clamp and a load that is applied somewhere other than where it was drawn.
    """
    el, faces, outer = _face_table(elements)
    if el.size == 0:
        return np.zeros(0, int)
    out = set(int(v) for v in faces[outer].ravel())
    if el.shape[1] >= 10:
        m = len(el)
        for k, f in enumerate(_TET_FACES):
            sel = outer[k * m:(k + 1) * m]
            if not sel.any():
                continue
            for a, b in ((f[0], f[1]), (f[1], f[2]), (f[0], f[2])):
                mid = _EDGE_MIDSIDE[(min(a, b), max(a, b))]
                out.update(int(v) for v in el[sel, mid])
    return np.array(sorted(out), int)


def _corner_points(xyz, elements, ids=None):
    """-> (m,4,3) corner coordinates of every tet.

    `xyz` may be a {node id: (x,y,z)} mapping or an (n,3) array. An array with
    no `ids` is taken to be indexed by node id minus one, which is what Gmsh
    writes; anything else must pass `ids` so the mapping is stated instead of
    guessed. An off-by-one here turns every tet inside out and still reports a
    perfectly plausible volume, because the volume is taken as |V|.
    """
    el = np.asarray(elements, int)[:, :4]
    if isinstance(xyz, dict):
        return np.array([[xyz[int(n)] for n in row] for row in el], float)
    pts = np.asarray(xyz, float)
    if ids is not None:
        lookup = {int(v): i for i, v in enumerate(np.asarray(ids, int))}
        idx = np.array([[lookup[int(n)] for n in row] for row in el], int)
    else:
        if el.size and (el.min() < 1 or el.max() > len(pts)):
            raise ValueError(
                "node ids %d..%d do not index %d rows of coordinates; pass "
                "ids= so the mapping is explicit"
                % (el.min(), el.max(), len(pts)))
        idx = el - 1
    return pts[idx] if len(el) else np.zeros((0, 4, 3))


def element_volumes(xyz, elements, ids=None):
    """|V| of every tet, mm^3. -> (m,) array.

    The absolute value is deliberate: an inverted element has a negative
    signed volume, and summing signed volumes would quietly *subtract* it from
    the total instead of showing it. Same node-id convention as
    `_corner_points`.
    """
    p = _corner_points(xyz, elements, ids)
    if len(p) == 0:
        return np.zeros(0)
    return np.abs(np.einsum("ij,ij->i", p[:, 1] - p[:, 0],
                            np.cross(p[:, 2] - p[:, 0],
                                     p[:, 3] - p[:, 0]))) / 6.0


# Consistent nodal weights for a uniform load on a quadratic tet / triangle.
# A 10-node tet under a uniform body force puts -1/20 of it on each corner
# and 1/5 on each mid-edge node; a 6-node triangle under a uniform traction
# puts nothing on the corners and 1/3 on each mid-edge node. Splitting the
# same load *equally* over the nodes instead is not a small approximation on
# these elements: it loads the corners, which the quadratic shape functions
# turn into a stress ripple at the loaded nodes -- the worst-element safety
# factor then belongs to the load split, not to the part (measured on
# osmo_tripod LC1: worst element 0.95 with an equal split where the voxel
# path had 5.3).
_C3D10_BODY_WEIGHTS = np.array([-1 / 20.0] * 4 + [1 / 5.0] * 6)
_TRI6_FACE_WEIGHTS = np.array([0.0, 0.0, 0.0, 1 / 3.0, 1 / 3.0, 1 / 3.0])
# Faces of a 10-node tet as (corner, corner, corner, mid, mid, mid) rows into
# the element's node list, Abaqus order (n5=(1,2) n6=(2,3) n7=(3,1) n8=(1,4)
# n9=(2,4) n10=(3,4)).
_C3D10_FACES = np.array([[0, 1, 2, 4, 5, 6],
                         [0, 1, 3, 4, 8, 7],
                         [1, 2, 3, 5, 9, 8],
                         [0, 2, 3, 6, 9, 7]])


def load_weights(xyz, elements, selected, mode, ids=None):
    """Consistent nodal weights (summing to 1) for a uniform load over the
    selected nodes. -> (weights {node id: w}, method string).

    `mode="volume"`: a uniform body force over every element whose ten nodes
    are all selected, weighted by element volume. `mode="surface"`: a uniform
    traction over every boundary face whose six nodes are all selected,
    weighted by face area. When nothing is fully inside the selection (a
    region smaller than an element) the caller gets an empty dict and falls
    back to an equal split -- and says so.
    """
    sel = set(int(v) for v in selected)
    if len(sel) == 0 or elements.shape[1] != 10:
        return {}, "equal"
    lookup = ({int(v): i for i, v in enumerate(ids)} if ids is not None
              else {i + 1: i for i in range(len(xyz))})
    w = {}
    if mode == "volume":
        vols = element_volumes(xyz, elements, ids)
        for e, vol in zip(elements, vols):
            if all(int(n) in sel for n in e):
                for n, c in zip(e, _C3D10_BODY_WEIGHTS):
                    w[int(n)] = w.get(int(n), 0.0) + float(vol) * c
        method = "consistent body force over %d fully selected elements"
    else:
        faces = []
        for e in elements:
            for f in _C3D10_FACES:
                faces.append(e[f])
        faces = np.array(faces, int)
        key = np.sort(faces[:, :3], axis=1)
        _, first, counts = np.unique(key, axis=0, return_index=True,
                                     return_counts=True)
        boundary = faces[first[counts == 1]]
        n_used = 0
        for f in boundary:
            if all(int(n) in sel for n in f):
                pts = xyz[[lookup[int(n)] for n in f[:3]]]
                area = 0.5 * np.linalg.norm(np.cross(pts[1] - pts[0],
                                                     pts[2] - pts[0]))
                n_used += 1
                for n, c in zip(f, _TRI6_FACE_WEIGHTS):
                    w[int(n)] = w.get(int(n), 0.0) + float(area) * c
        method = "consistent traction over %d fully selected boundary faces"
    total = sum(w.values())
    if total <= 0:
        return {}, "equal"
    count = (len([1 for e in elements if all(int(n) in sel for n in e)])
             if mode == "volume" else n_used)
    return {k: v / total for k, v in w.items()}, method % count


def mesh_quality(xyz_by_index, elements, ids=None):
    """Per-tet shape quality on the corner nodes. -> dict.

    q = 12 (3V)^(2/3) / sum(edge^2) is 1 for a regular tet and tends to 0 for
    a sliver. It is reported because a mesh full of slivers does not fail: it
    solves, and then reports a stress that is a property of its worst elements
    rather than of the part. |V| is used so an inverted element is judged on
    its shape and appears in the count instead of raising.

    `pass` is deliberately two conditions, not one: fewer than 0.5 % of the
    elements below 0.02 (a sliver is enough to own the stress maximum, so
    they are counted separately as `sliver_count`) *and* fewer than 5 %
    below 0.1. The bars are set from real meshes, not from taste: a shell
    refined to the target size and meshed with HXT (osmo_tripod) has
    0.16 % / 2.9 % at 4 mm and 0.013 % / 1.2 % at 2 mm, and its boundary
    triangles are the ones OpenSCAD exported -- long and thin on every
    cylinder wall -- so "no sliver at all" would fail every STL this tool
    will ever see. A mesh that trips these bars is genuinely bad.
    """
    p = _corner_points(xyz_by_index, elements, ids)
    if len(p) == 0:
        return {"min": None, "p1": None, "p5": None, "median": None,
                "poor_count": 0, "poor_fraction": 0.0, "elements": 0,
                "pass": False, "note": "the mesh has no elements"}
    v = np.abs(np.einsum("ij,ij->i", p[:, 1] - p[:, 0],
                         np.cross(p[:, 2] - p[:, 0], p[:, 3] - p[:, 0]))) / 6.0
    e2 = np.zeros(len(p))
    for a, b in ((0, 1), (0, 2), (0, 3), (1, 2), (1, 3), (2, 3)):
        d = p[:, b] - p[:, a]
        e2 += np.einsum("ij,ij->i", d, d)
    q = np.where(e2 > 0,
                 12.0 * np.cbrt((3.0 * v) ** 2) / np.maximum(e2, 1e-30), 0.0)
    poor = int((q < 0.1).sum())
    frac = poor / float(len(q))
    slivers = int((q < 0.02).sum())
    sliver_frac = slivers / float(len(q))
    ok = bool(sliver_frac < 0.005 and frac < 0.05)
    return {"min": round(float(q.min()), 5),
            "sliver_count": slivers, "sliver_fraction": round(sliver_frac, 6),
            "p1": round(float(np.percentile(q, 1)), 5),
            "p5": round(float(np.percentile(q, 5)), 5),
            "median": round(float(np.median(q)), 5),
            "poor_count": poor, "poor_fraction": round(frac, 5),
            "elements": int(len(q)), "pass": ok,
            "note": ("no sliver elements" if ok else
                     "the mesh contains sliver elements; the stress maximum "
                     "may be a property of the worst element rather than of "
                     "the part")}


def mass_properties(xyz, elements, density_kg_m3, ids=None):
    """Volume, mass, centroid and inertia of the meshed solid.

    -> {"volume_mm3", "mass_g", "centroid_mm", "inertia_tensor_g_mm2",
        "elements"}, the inertia taken about the centroid.

    The second moments are integrated over each tet exactly -- the barycentric
    identity int(li*lj) dV = V (1 + delta_ij) / 20 -- rather than approximated
    by putting each tet's mass at its own centroid. The point-mass version is
    short by exactly the tets' own inertia, which is percent-level on a coarse
    mesh and always *low*: the direction that makes a part look easier to spin
    up, and to shake, than it is.

    Density arrives in kg/m^3 (the one quantity in this codebase that is not
    mm/N/MPa, because `materials.py` states it that way) and is converted
    here: 1 kg/m^3 = 1e-6 g/mm^3.
    """
    p = _corner_points(xyz, elements, ids)
    if len(p) == 0:
        raise ValueError("no elements -- there is nothing to weigh")
    vol6 = np.einsum("ij,ij->i", p[:, 1] - p[:, 0],
                     np.cross(p[:, 2] - p[:, 0], p[:, 3] - p[:, 0]))
    v = np.abs(vol6) / 6.0
    total = float(v.sum())
    centroid = (v[:, None] * p.mean(axis=1)).sum(axis=0) / total
    q = p - centroid                            # integrate about the centroid
    s = q.sum(axis=1)                           # (m,3)
    cov = (v[:, None, None] / 20.0) * (np.einsum("ia,ib->iab", s, s)
                                       + np.einsum("ika,ikb->iab", q, q))
    c = cov.sum(axis=0)
    rho_g_mm3 = float(density_kg_m3) * 1e-6
    inertia = rho_g_mm3 * (np.trace(c) * np.eye(3) - c)
    return {"volume_mm3": round(total, 6),
            "mass_g": round(total * rho_g_mm3, 6),
            "centroid_mm": [round(float(x), 6) for x in centroid],
            "inertia_tensor_g_mm2": [[round(float(x), 6) for x in row]
                                     for row in inertia],
            "elements": int(len(v))}


# ------------------------------------------------------------ material card

def ortho_constants(ortho, build_axis=2, raster_axis=None):
    """The nine numbers for `*ELASTIC, TYPE=ORTHO`, in CalculiX's order.

    CalculiX wants
        D1111 D1122 D2222 D1133 D2233 D3333 D1212 D1313 D2323
    i.e. the upper triangle of the normal block read column by column, then
    shear xy, zx, yz. This module's Voigt order is [xx,yy,zz,xy,yz,zx], so the
    last three are D[3,3], D[5,5], D[4,4] -- not D[3,3], D[4,4], D[5,5].
    Writing that mapping out is the whole point of this function: an off-by-one
    here produces a model that solves happily and is wrong about which
    direction is weak.
    """
    from .hex8 import orthotropic_D
    D, _ = orthotropic_D(ortho, build_axis, raster_axis, normalise=False)
    return [D[0, 0], D[0, 1], D[1, 1], D[0, 2], D[1, 2], D[2, 2],
            D[3, 3],      # D1212 = xy   (this module's Voigt slot 3)
            D[5, 5],      # D1313 = zx   (slot 5, NOT slot 4)
            D[4, 4]]      # D2323 = yz   (slot 4)


def material_block(name, ortho=None, E=None, nu=None, density_kg_m3=None,
                   build_axis=2, raster_axis=None):
    """The `*MATERIAL` block, orthotropic or isotropic.

    Density is written in tonne/mm^3 because the deck is in mm/N/MPa: getting
    this wrong scales every buckling factor and every natural frequency by 10^9
    while the static results stay perfect, so it would survive a static check.
    """
    lines = ["*MATERIAL, NAME=%s" % name]
    if ortho is not None:
        c = ortho_constants(ortho, build_axis, raster_axis)
        lines.append("*ELASTIC, TYPE=ORTHO")
        lines.append(", ".join("%.6g" % v for v in c[:8]))
        lines.append("%.6g" % c[8])
        rho = ortho.density_kg_m3
    else:
        if E is None or nu is None:
            raise ValueError("isotropic material needs both E and nu")
        lines.append("*ELASTIC, TYPE=ISO")
        lines.append("%.6g, %.6g" % (E, nu))
        rho = density_kg_m3
    if rho:
        # kg/m^3 -> tonne/mm^3
        lines.append("*DENSITY")
        lines.append("%.6g" % (float(rho) * 1e-12))
    return "\n".join(lines)


# ---------------------------------------------------------------- the deck

# The element set the deck's *SOLID SECTION points at. Gmsh names the set
# after the physical volume in GEO_TEMPLATE, so the two have to agree: the
# first real run (2026-09-08, ccx 2.23) stopped at "element set EALL has not
# yet been defined" because the deck assumed a set Gmsh never writes.
MESH_ELSET = "part"


def write_inp(path, mesh_inp, material, cases, analyses=("static",),
              nset_fix="FIXED", elset=MESH_ELSET):
    """Assemble a CalculiX deck from a Gmsh mesh and the load cases.

    `cases` is a list of dicts with `name`, `fixed_nodes` (iterable of node
    ids), and `loads` (list of (node_id, (fx, fy, fz))). Node ids are 1-based,
    matching the mesh file.

    Two optional keys extend that:

    - `supports`: a list of ``{"nodes": [...], "dofs": (1, 2, 3)}``, one node
      set per entry, when different parts of the boundary are held in
      different directions. A pin that is written as a full clamp is the
      commonest way to make a part look stiffer than it is, and `fixed_nodes`
      can only say "all three". When `supports` is given it replaces
      `fixed_nodes`.
    - `gravity`: ``[gx, gy, gz]`` in mm/s^2, written as ``*DLOAD`` / ``GRAV``
      in the static and buckling steps. Never in the frequency step: modes are
      a property of mass and stiffness, and a load there would be ignored at
      best. It is refused outright when the material card has no `*DENSITY`,
      because CalculiX would otherwise apply a body force of zero and report a
      perfectly converged answer to a question nobody asked.

      One consequence to know before quoting an equilibrium error on a case
      with gravity: the `total force` CalculiX prints for a support set is the
      *net* nodal force there, so the share of the body force that lands on
      the supported nodes themselves is already subtracted from it. Measured
      on the 20x10x5 box (weight 0.012160 N): the printed total was 0.011046 N
      and the missing 0.001114 N was the gravity carried by the clamped nodes.
      The balance is exact for `*CLOAD` and short by that much for `GRAV`.

    Every step asks for reaction forces (`RF`) as well as displacement and
    stress, because the load/reaction balance in `equilibrium_error` is the
    only cheap check that the boundary conditions in the deck are the ones
    that were intended.
    """
    if not cases:
        raise ValueError("no load cases -- nothing to analyse")
    out = ["*INCLUDE, INPUT=%s" % os.path.basename(mesh_inp), material,
           "*SOLID SECTION, ELSET=%s, MATERIAL=%s"
           % (elset, _material_name(material))]
    has_density = "*DENSITY" in material

    for i, case in enumerate(cases, 1):
        supports = _support_sets(case, i, nset_fix)
        loads = list(case.get("loads") or ())
        grav = case.get("gravity")
        if grav is not None:
            grav = [float(v) for v in grav]
            if not has_density:
                raise ValueError(
                    "case %r asks for gravity but the material card has no "
                    "*DENSITY; CalculiX would apply a body force of zero and "
                    "report it as converged" % case.get("name"))
            if not any(abs(v) > 0 for v in grav):
                grav = None
        # A frequency-only deck has no load *by design*: modes are a property
        # of mass and stiffness, and the step below writes no `*CLOAD` for
        # them anyway. Refusing it here would force the caller to hand over a
        # load the writer then throws away -- and the day someone asks for
        # ("static", "frequency") that smuggled load would silently reappear
        # in the static step.
        if not loads and grav is None and any(k != "frequency"
                                              for k in analyses):
            raise ValueError("case %r has no loads" % case.get("name"))
        for tag, nodes, _dofs in supports:
            out.append("*NSET, NSET=%s" % tag)
            out.append(_wrap(nodes))

        for kind in analyses:
            out.append("*STEP")
            if kind == "static":
                out.append("*STATIC")
            elif kind == "buckle":
                out.append("*BUCKLE")
                out.append("4")            # first four buckling factors
            elif kind == "frequency":
                out.append("*FREQUENCY")
                out.append("6")            # first six modes
            else:
                raise ValueError("unknown analysis %r" % kind)
            # OP=NEW on both cards. CalculiX carries boundary conditions and
            # concentrated loads over from one *STEP to the next unless told
            # otherwise, so without it case 2 is solved with case 1's clamp
            # and load still applied, case 3 with both, and by the fourth
            # case the part is held everywhere and barely moves. The first
            # real run (2026-09-08) reported 0.02 mm and safety factor 11 for
            # every case after the second; the voxel FEA had 2.8 mm and 2.0.
            out.append("*BOUNDARY, OP=NEW")
            for tag, _nodes, dofs in supports:
                out.extend(_boundary_lines(tag, dofs))
            if kind != "frequency" and loads:
                out.append("*CLOAD, OP=NEW")
                for nid, f in loads:
                    for d in range(3):
                        if abs(f[d]) > 0:
                            out.append("%d, %d, %.8g" % (int(nid), d + 1, f[d]))
            if kind != "frequency" and grav is not None:
                mag = float(np.linalg.norm(grav))
                out.append("*DLOAD, OP=NEW")
                out.append("%s, GRAV, %.8g, %.8g, %.8g, %.8g"
                           % (elset, mag, grav[0] / mag, grav[1] / mag,
                              grav[2] / mag))
            out.append("*NODE FILE")
            out.append("U, RF")
            out.append("*EL FILE")
            out.append("S, E")
            for tag, _nodes, _dofs in supports:
                out.append("*NODE PRINT, NSET=%s, TOTALS=ONLY" % tag)
                out.append("RF")
            out.append("*END STEP")

    txt = "\n".join(out) + "\n"
    with open(path, "w", encoding="utf-8") as f:
        f.write(txt)
    return path


def _material_name(block):
    m = re.search(r"\*MATERIAL,\s*NAME=(\S+)", block)
    return m.group(1) if m else "MAT"


def _support_sets(case, i, nset_fix):
    """-> [(nset name, sorted node ids, dofs), ...] for one case.

    `supports` wins over `fixed_nodes` when both are present, because the
    caller that wrote the richer key meant it. The naming is deliberately
    different -- FIXED1 for the legacy single clamp, FIXED1_1 for the first
    of several -- so the same deck comes out byte for byte as before for a
    caller that never heard of `supports`.
    """
    name = case.get("name")
    sups = case.get("supports")
    if sups:
        out = []
        for j, sup in enumerate(sups, 1):
            nodes = sorted(set(int(n) for n in (sup.get("nodes") or ())))
            if not nodes:
                raise ValueError(
                    "case %r has a support with no nodes -- the part would "
                    "float away and the solve would be singular" % name)
            dofs = tuple(sorted(set(int(d) for d in
                                    (sup.get("dofs") or (1, 2, 3)))))
            if not dofs or min(dofs) < 1 or max(dofs) > 3:
                raise ValueError("case %r has a support with dofs %r; only "
                                 "1, 2 and 3 exist on a solid element"
                                 % (name, sup.get("dofs")))
            out.append(("%s%d_%d" % (nset_fix, i, j), nodes, dofs))
        return out
    fixed = sorted(set(int(n) for n in case.get("fixed_nodes", ())))
    if not fixed:
        raise ValueError("case %r has no fixed nodes -- the part would "
                         "float away and the solve would be singular" % name)
    return [("%s%d" % (nset_fix, i), fixed, (1, 2, 3))]


def _boundary_lines(tag, dofs):
    """`*BOUNDARY` rows for one node set, contiguous dof ranges collapsed.

    CalculiX reads `nset, first_dof, last_dof, value` as a *range*, so a
    support that holds 1 and 3 but not 2 cannot be written as one line: doing
    so silently clamps the direction that was meant to be free.
    """
    rows, run = [], []
    for d in list(dofs) + [None]:
        if run and d == run[-1] + 1:
            run.append(d)
            continue
        if run:
            rows.append("%s, %d, %d, 0.0" % (tag, run[0], run[-1]))
        run = [d] if d is not None else []
    return rows


def _wrap(ids, per_line=8):
    rows = []
    for i in range(0, len(ids), per_line):
        rows.append(", ".join(str(v) for v in ids[i:i + per_line]))
    return "\n".join(rows)


def run_ccx(inp_path, timeout=7200):
    """-> (stdout, base path without extension). ToolMissing -> exit code 3."""
    exe = require("calculix", "the independent re-analysis")
    base = os.path.splitext(inp_path)[0]
    r = subprocess.run([exe, os.path.basename(base)],
                       cwd=os.path.dirname(os.path.abspath(inp_path)) or ".",
                       capture_output=True, text=True, timeout=timeout)
    out = (r.stdout or "") + (r.stderr or "")
    # CalculiX returns 0 even for a diverged job, so the text is the verdict.
    if "*ERROR" in out or not os.path.exists(base + ".frd"):
        raise RuntimeError("CalculiX did not produce results:\n%s"
                           % out[-4000:])
    return out, base


def converged(ccx_output):
    """-> (bool, reason). A non-converged run must never be shown as a pass."""
    bad = [("*ERROR", "CalculiX reported an error"),
           ("did not converge", "the solve did not converge"),
           ("singular", "the stiffness matrix is singular -- check supports")]
    low = ccx_output.lower()
    for needle, why in bad:
        if needle.lower() in low:
            return False, why
    return True, "no error or divergence reported"


